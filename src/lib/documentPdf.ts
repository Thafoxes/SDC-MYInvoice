/** Lightweight client-side, single/multi-page A4 PDF exporter for synthetic demo records.
 * Helvetica/ASCII; use a dedicated PDF renderer for production multilingual documents. */
const ascii=(value:unknown)=>String(value??'').replace(/[^\x20-\x7e]/g,'?');
const esc=(value:string)=>ascii(value).replace(/\\/g,'\\\\').replace(/\(/g,'\\(').replace(/\)/g,'\\)');
function wrap(line:string, max=84):string[]{
 const chunks:string[]=[]; let rest=ascii(line);
 while(rest.length>max){let idx=rest.lastIndexOf(' ',max);if(idx<30)idx=max;chunks.push(rest.slice(0,idx));rest=rest.slice(idx).trimStart();}
 chunks.push(rest);return chunks;
}
export function downloadDocumentPdf(filename:string,title:string,sections:{heading:string;lines:string[]}[]){
 const content:string[]=[];
 content.push(title,'Generated by NudgeWise for seller review','');
 for(const group of sections){content.push('--- '+group.heading+' ---');for(const line of group.lines)content.push(...wrap(line));content.push('');}
 content.push('Business document: verify all terms and applicable regulatory requirements before use.');
 const pages:string[][]=[];for(let i=0;i<content.length;i+=45)pages.push(content.slice(i,i+45));
 const objects:string[]=['', '<< /Type /Catalog /Pages 2 0 R >>', '', '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'];
 const references:number[]=[];
 for(let page=0;page<pages.length;page++){
  const pageId=objects.length;
  const streamId=pageId+1;
  const cmds=pages[page].map((line,i)=>`BT /F1 ${i===0&&page===0?17:10} Tf 42 ${795-i*16} Td (${esc(line)}) Tj ET`).join('\n');
  objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R >> >> /Contents ${streamId} 0 R >>`);
  objects.push(`<< /Length ${new TextEncoder().encode(cmds).length} >>\nstream\n${cmds}\nendstream`);
  references.push(pageId);
 }
 objects[2]=`<< /Type /Pages /Kids [${references.map(i=>`${i} 0 R`).join(' ')}] /Count ${references.length} >>`;
 const encoder=new TextEncoder();let src='%PDF-1.4\n';const offsets=[0];
 for(let i=1;i<objects.length;i++){offsets.push(encoder.encode(src).length);src+=`${i} 0 obj\n${objects[i]}\nendobj\n`;}
 const start=encoder.encode(src).length;
 src+=`xref\n0 ${objects.length}\n0000000000 65535 f \n`;
 for(let i=1;i<objects.length;i++)src+=`${String(offsets[i]).padStart(10,'0')} 00000 n \n`;
 src+=`trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${start}\n%%EOF`;
 const blob=new Blob([encoder.encode(src)],{type:'application/pdf'});
 const url=URL.createObjectURL(blob);const a=document.createElement('a');a.href=url;a.download=filename.replace(/[^a-z0-9_.-]/gi,'_');document.body.append(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(url),1000);
}
